// ── сборка ──────────────────────────────────────────────────────────
var nomer = 0, DESK = [];
function snoska(text, spisok) {
  (spisok || []).forEach(function (s) {
    var i = text.indexOf(s.posle);
    if (i < 0) throw new Error('не нашёл место сноски «' + s.posle + '»');
    nomer++;
    DESK.push({ n: nomer, text: s.d });
    var kon = i + s.posle.length;
    text = text.slice(0, kon) + '⟦' + nomer + '⟧' + text.slice(kon);
  });
  return text;
}

var vyhod = { titul: PLAN.titul, img: '/gorizont-img/', chasti: [], deskriptory: DESK };
PLAN.chasti.forEach(function (ch) {
  var tok = ch.tok.map(function (z) {
    if (z.t === 'text') return { t: 'text', adres: z.k, text: snoska(ru(z.k), z.snoski) };
    if (z.t === 'fig') {
      var g = kart(z.src);
      return { t: 'fig', src: g.src, w: g.w, h: g.h, poz: z.poz || 'c',
               podpis: z.cap ? ru(z.cap) : null };
    }
    if (z.t === 'ryad') {
      return { t: 'ryad', items: z.items.map(kart), poz: z.poz || 'c',
               podpis: z.cap ? ru(z.cap) : null };
    }
    return z;                       // tezis, citata, pod — как написаны
  });
  vyhod.chasti.push({ id: ch.id, nazvanie: ch.nazvanie, tok: tok });
});

