/* ────────────────────────────────────────────────────────────────────
   СБОРЩИК ЛЕКЦИИ ИЗ СТАТЬИ.
   Читает материал стенда «Горизонтальный лонгрид» (gorizont-data.js —
   порядок и картинки, gorizont-ru.js — русский текст) и раскладывает его
   по ПЛАНУ ниже в формат стенда «Лекция»: части, тезисы, цитаты,
   подзаголовки, сноски с дескрипторами, картинки с подписями.

   ПЛАН — единственное, что пишется руками. Тексты не перепечатываются:
   фрагмент берётся по своему адресу («01 – 05»), подпись — по ключу
   («cap-04»). Отсюда же вырастут будущие правила «статья → лекция».

   Сноска объявляется парой: где встать (подстрока в тексте) и что сказать
   (дескриптор). Нумерация сквозная по всей лекции, маркер в тексте — ⟦N⟧.

   Запуск:  node ~/stendy/lekciya-sobrat.js   →  ~/stendy/lekciya-data.js
   ──────────────────────────────────────────────────────────────────── */
var fs = require('fs');
var put = __dirname + '/';

// ── материал ────────────────────────────────────────────────────────
var okno = {};
new Function('window', fs.readFileSync(put + 'gorizont-data.js', 'utf8'))(okno);
new Function('window', fs.readFileSync(put + 'gorizont-ru.js', 'utf8'))(okno);
var LENTA = okno.GORIZONT, RU = okno.GORIZONT_RU;

var KARTINKI = {};   // адрес картинки → натуральные размеры из ленты
LENTA.forEach(function (z) {
  if (z.t === 'fig' && z.src) KARTINKI[z.src] = { w: z.w, h: z.h };
  if (z.t === 'figs') (z.items || []).forEach(function (i) { KARTINKI[i.src] = { w: i.w, h: i.h }; });
});
function ru(k) {
  if (!RU[k]) throw new Error('нет русского текста: ' + k);
  return RU[k].text;
}
function kart(src) {
  var g = KARTINKI[src];
  // схема, которую лента рисует кодом, лежит в папке файлом: пропорцию
  // берём из самого svg — место под картинку держит она, а не догадка
  if (!g && /\.svg$/.test(src)) {
    var t = fs.readFileSync(put + 'gorizont-img/' + src, 'utf8').slice(0, 400);
    var w = /width="(\d+(?:\.\d+)?)"/.exec(t), h = /height="(\d+(?:\.\d+)?)"/.exec(t);
    if (w && h) g = { w: +w[1], h: +h[1] };
  }
  if (!g) throw new Error('нет картинки в ленте: ' + src);
  return { src: src, w: g.w, h: g.h };
}

